/**
 * The private Persian font, kept out of this public repository.
 *
 * IRANSansX is licensed to the owner for application use; it is not open source
 * and must never be committed here. `src/assets/fonts/private/` is git-ignored.
 * This step runs before dev, lint, typecheck and build:
 *
 * 1. With LUMO_PRIVATE_FONTS_DIR set, it copies every `private` entry of
 *    docs/site-assets.json (the font and its licence note) from that directory
 *    into the ignored one. A missing file there is an error: the variable is a
 *    request for the private build.
 * 2. When the font is present (copied now, or kept from an earlier run), its
 *    bytes and its licence note are verified against the reviewed checksums.
 * 3. It writes the ignored `persian-font.ts` module the layout imports: a
 *    `next/font/local` declaration over the private file, or — without the
 *    font — a stub whose variable leaves `--font-persian` unset, so the CSS
 *    falls back to the system Persian stack declared in `src/app/globals.css`.
 *
 * LUMO_REQUIRE_PRIVATE_FONTS=1 turns a missing font into an error, for the
 * production image. A public clone builds without either variable.
 */
import { createHash } from "node:crypto";
import { copyFile, mkdir, readFile, writeFile } from "node:fs/promises";
import { existsSync } from "node:fs";
import { basename, isAbsolute, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const app = fileURLToPath(new URL("../", import.meta.url));

export const GENERATED = "src/assets/fonts/private/persian-font.ts";

const header = `// GENERATED by scripts/prepare-private-fonts.mjs. Git-ignored: never commit.\n`;

export const PRIVATE_MODULE = `${header}import localFont from "next/font/local";

export const persian = localFont({ src: "./IRANSansXVF.woff2", variable: "--font-persian", display: "block", weight: "100 1000", adjustFontFallback: false });
`;

export const FALLBACK_MODULE = `${header}// The private IRANSansX font is absent, so --font-persian stays unset and
// src/app/globals.css serves its system Persian stack instead.
export const persian = { variable: "lumo-persian-system-font" } as const;
`;

const sha256 = (data) => createHash("sha256").update(data).digest("hex");

export async function preparePrivateFonts({ root = app, env = process.env, log = console.log } = {}) {
  const manifest = JSON.parse(await readFile(resolve(root, "docs/site-assets.json"), "utf8"));
  const directory = manifest.privateAssets?.directory;
  if (directory !== "src/assets/fonts/private") throw new Error("docs/site-assets.json must name the ignored private font directory");
  const privateFiles = manifest.files.filter((file) => file.private === true);
  const font = privateFiles.find((file) => file.role === "font");
  if (!font || !privateFiles.some((file) => file.path === font.notice)) {
    throw new Error("docs/site-assets.json must list the private font and its licence note");
  }
  for (const file of privateFiles) {
    const within = relative(resolve(root, directory), resolve(root, file.path));
    if (within.startsWith("..") || isAbsolute(within)) throw new Error(`A private asset must stay in ${directory}: ${file.path}`);
  }
  await mkdir(resolve(root, directory), { recursive: true });

  const source = env.LUMO_PRIVATE_FONTS_DIR?.trim();
  if (source) {
    for (const file of privateFiles) {
      const from = resolve(source, basename(file.path));
      if (!existsSync(from)) throw new Error(`LUMO_PRIVATE_FONTS_DIR has no ${basename(file.path)} (looked in ${resolve(source)})`);
      await copyFile(from, resolve(root, file.path));
    }
  }

  const present = existsSync(resolve(root, font.path));
  if (present) {
    for (const file of privateFiles) {
      const path = resolve(root, file.path);
      if (!existsSync(path)) throw new Error(`The private font needs its licence note beside it: ${file.path}`);
      if (sha256(await readFile(path)) !== file.sha256) {
        throw new Error(`Private asset does not match its reviewed checksum: ${file.path}`);
      }
    }
  } else if (env.LUMO_REQUIRE_PRIVATE_FONTS === "1") {
    throw new Error("LUMO_REQUIRE_PRIVATE_FONTS=1 but the private Persian font is absent; set LUMO_PRIVATE_FONTS_DIR");
  }

  const generated = present ? PRIVATE_MODULE : FALLBACK_MODULE;
  const target = resolve(root, GENERATED);
  const current = existsSync(target) ? await readFile(target, "utf8") : "";
  // Rewrite only on change, so a dev server does not reload on every run.
  if (current !== generated) await writeFile(target, generated);
  const mode = present ? "private" : "fallback";
  log(mode === "private"
    ? "Persian font: private IRANSansX verified (git-ignored, never committed)."
    : "Persian font: private IRANSansX absent; serving the system Persian fallback. Set LUMO_PRIVATE_FONTS_DIR for the private build.");
  return mode;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  await preparePrivateFonts();
}
